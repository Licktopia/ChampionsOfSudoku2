import com.amazonaws.mobileconnectors.dynamodbv2.dynamodbmapper.*;
import com.licktopia.thechampionofsudoku.Gamer;
import com.amazonaws.mobileconnectors.dynamodbv2.dynamodbmapper.DynamoDBHashKey;


@DynamoDBTable(tableName = "CompletedGame")
public class CompletedGame {
    private String gameID;
    private String gamerID;
    private int realScore;
    private int time;
    private String date;
    private boolean color;
    private int puzzleNumber;
    private int level;
    private double accuracy;
    private int xp;


    @DynamoDBHashKey(attributeName = "GameID")
    @DynamoDBAutoGeneratedKey
    public String getGameID() {
        return gameID;
    }

    public void setGameID(String gameID) {
        this.gameID = gameID;
    }

    @DynamoDBHashKey(attributeName = "GamerID")
    public String getGamerID() {
        return gamerID;
    }

    public void setGamerID(String gamerID) {
        this.gamerID = gamerID;
    }

    @DynamoDBAttribute(attributeName = "RealScore")
    public int getRealScore() {
        return realScore;
    }

    public void setRealScore(int realScore) {
        this.realScore = realScore;
    }

    @DynamoDBAttribute(attributeName = "Xp")
    public int getXp() {
        return xp;
    }

    public void setXp(int xp) {
        this.xp = xp;
    }

    @DynamoDBAttribute(attributeName = "Time")
    public int getTime() {
        return time;
    }

    public void setTime(int time) {
        this.time = time;
    }

    @DynamoDBAttribute(attributeName = "Date")
    public String getDate() {
        return date;
    }


    public void setDate(String date) {
        this.date = date;
    }

    @DynamoDBAttribute(attributeName = "Color")
    public boolean isColor() {
        return color;
    }

    public void setColor(boolean color) {
        this.color = color;
    }

    @DynamoDBAttribute(attributeName = "PuzzleNo")
    public int getPuzzleNumber() {
        return puzzleNumber;
    }

    public void setPuzzleNumber(int puzzleNumber) {
        this.puzzleNumber = puzzleNumber;
    }

    @DynamoDBAttribute(attributeName = "Level")
    public int getLevel() {
        return level;
    }

    public void setLevel(int level) {
        this.level = level;
    }

    @DynamoDBAttribute(attributeName = "Accuracy")
    public double getAccuracy() {
        return accuracy;
    }

    public void setAccuracy(double accuracy) {
        this.accuracy = accuracy;
    }


}